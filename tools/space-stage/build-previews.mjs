// Generate binary asset declarations from actual rendered scene previews.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const names = readdirSync(resolve(root, 'plugin/ui/space-scene-preview')).filter(name => /^[a-z][a-z0-9-]*\.jpg$/.test(name)).sort();
if (!names.length) throw new Error('Render scene previews before generating their embedded declarations');
const output = '// SPDX-License-Identifier: MIT\n// Generated by tools/space-stage/build-previews.mjs; filenames own this binary asset list.\n' +
  '// rustfmt would split each entry onto four lines; one row per preview is the point.\n#[rustfmt::skip]\n' +
  'pub(super) const PREVIEWS: &[(&str, &[u8])] = &[\n' + names.map(name =>
    `    ("${name}", include_bytes!("../../../plugin/ui/space-scene-preview/${name}")),`).join('\n') + '\n];\n';
writeFileSync(resolve(root, 'crates/hertz-studio/src/space_previews.rs'), output);
console.log(`Embedded ${names.length} actual scene previews`);
