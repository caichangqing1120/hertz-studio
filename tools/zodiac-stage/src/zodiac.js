// 第 index 座在黄道环上的位姿（纯函数）。返回方位角与环面坐标；
// 星图平面朝向环心（背面也渲染，点/线无朝向剔除）。
export function ringTransform(index, count, radius) {
  const n = count || SIGN_COUNT;
  const i = ((index % n) + n) % n;
  const angle = (i / n) * Math.PI * 2;
  const r = radius || RING_RADIUS;
  return { index: i, angle, x: Math.sin(angle) * r, z: Math.cos(angle) * r, radius: r };
}

// 某颗星相对星图平面的景深（纯函数，种子化）：让平面星图变成立体造型。
export function starDepth(signId, starIndex, spread) {
  const rnd = seededRandom('zodiac-depth:' + signId + ':' + starIndex);
  return (rnd() - 0.5) * 2 * (spread == null ? DEPTH_SPREAD : spread);
}

// 把局部星图坐标换算为星座局部 3D 坐标（纯函数）。
export function localStar(star, signId, starIndex) {
  return [star[0] * SIGN_SCALE, star[1] * SIGN_SCALE, starDepth(signId, starIndex)];
}

// 低频能量：前 5 个对数频带的均值，夹在 0..1。
export function viewBass(bins) {
  if (!bins || !bins.length) return 0;
  let sum = 0;
  const n = Math.min(5, bins.length);
  for (let i = 0; i < n; i += 1) sum += clamp(Number(bins[i]) || 0);
  return clamp(sum / n);
}

// 缩放距离钳制（纯函数）：拖拽/滚轮的取值边界唯一处。
export function zoomClamp(dist, minDist, maxDist) {
  return clamp(dist, minDist || 3, maxDist || 17);
}
