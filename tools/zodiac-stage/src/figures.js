const region = (outline, holes = []) => ({ outline, holes });
const oval = (cx, cy, rx, ry, n = 18) => Array.from({ length: n }, (_, i) => {
  const a = i / n * Math.PI * 2;
  return [cx + Math.cos(a) * rx, cy + Math.sin(a) * ry];
});
const stroke = (path, width) => {
  const side = sign => path.map((p, i) => {
    const a = path[Math.max(0, i - 1)], b = path[Math.min(path.length - 1, i + 1)];
    const length = Math.hypot(b[0] - a[0], b[1] - a[1]);
    return [p[0] - (b[1] - a[1]) / length * width / 2 * sign,
      p[1] + (b[0] - a[0]) / length * width / 2 * sign];
  });
  return region([...side(1), ...side(-1).reverse()]);
};
