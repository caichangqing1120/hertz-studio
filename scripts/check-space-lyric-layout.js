'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const load = file => import(pathToFileURL(path.resolve(__dirname, '../tools/space-stage', file)).href);

(async () => {
  const { layoutLyricText, lyricFill } = await load('src/scenes/text-layout.js');
  const context = { measureText: text => ({ width: Array.from(text).reduce((sum, char) => sum + (/\s/.test(char) ? 28 : char.charCodeAt(0) > 255 ? 112 : 60), 0) }) };
  const sentence = '\u5728\u661f\u5149\u4e0b\u542c\u89c1\u8fd9\u5ea7\u57ce\u5e02\u7684\u56de\u58f0\uff0c\u8ba9\u97f3\u4e50\u5e26\u6211\u4eec\u53bb\u8fdc\u65b9';
  const layout = layoutLyricText(context, sentence, 'sans-serif');
  assert.ok(layout.rows.length > 1, 'long Chinese lyrics wrap instead of shrinking into a thin strip');
  assert.equal(layout.rows.map(row => sentence.slice(row.start, row.end)).join(''), sentence, 'wrapping preserves every character');
  assert.ok(layout.rows.every(row => row.width <= layout.width - layout.padding * 2), 'all rows fit the texture');
  assert.ok(layout.fontSize >= 96, 'long lyrics retain readable glyph resolution');
  const responsiveMetrics = { measureText(text) { return { width: Array.from(text).length * (Number(this.font.match(/(\d+)px/)?.[1]) || 112) }; } };
  const longest = layoutLyricText(responsiveMetrics, '\u661f'.repeat(120), 'sans-serif');
  assert.ok(longest.rows.length <= 4, 'the maximum-length lyric fits all four shader highlight lanes');
  const portrait = layoutLyricText(responsiveMetrics, sentence, 'sans-serif', 896);
  assert.ok(portrait.rows.length > layout.rows.length, 'portrait wraps to fewer characters per row');
  assert.ok(portrait.fontSize >= 96, 'portrait retains native glyph resolution for normal long sentences');
  assert.ok(layoutLyricText(responsiveMetrics, '\u661f'.repeat(120), 'sans-serif', 896).rows.length <= 6, 'portrait maximum fits the six available highlight lanes');
  const emoji = layoutLyricText(context, 'A\ud83c\udfb5B '.repeat(15), 'sans-serif');
  assert.ok(emoji.rows.every(row => !/[\uD800-\uDBFF]$/.test(emoji.text.slice(row.start, row.end))), 'wrapping never splits a surrogate pair');
  const text = 'We   sing, together';
  const measured = layoutLyricText(context, text, 'sans-serif');
  const line = { text, tokens: [{ text: 'We', start: 0, end: 1 }, { text: 'sing', start: 2, end: 4 }, { text: 'together', start: 5, end: 8 }] };
  const fill = lyricFill(measured, line, 3, .5);
  const expected = measured.rows[0].advances[text.indexOf('sing') + 2];
  assert.ok(Math.abs(fill[0] - expected) < 1e-6, 'native token timings preserve source spaces and punctuation');
  assert.ok(lyricFill(measured, line, -1, 0)[0] < measured.rows[0].left, 'no character is highlighted before the first token');
  assert.ok(lyricFill(measured, line, 9, 1)[0] >= measured.rows[0].right, 'last token completion fills the complete row');
  const THREE = await load('node_modules/three/build/three.module.js');
  const { createScope } = await load('src/scope.js');
  const { createSpatialLyrics } = await load('src/scenes/text.js');
  const { createSpatialResources } = await load('src/scenes/resources.js');
  global.document = { createElement: () => ({ getContext: () => ({ ...context, fillText() {} }) }) };
  const scene = new THREE.Scene(), scope = createScope(), camera = new THREE.PerspectiveCamera(58, 16 / 9);
  camera.position.z = 15;
  const resources = createSpatialResources(THREE);
  const instance = createSpatialLyrics({ THREE, scene, scope, camera, params: {}, quality: { density: 1 }, services: { spatialResources: resources } });
  const lines = Array.from({ length: 5 }, (_, i) => ({ text: 'Row ' + i, start: i * 4, end: (i + 1) * 4 }));
  const frame = { now: 1000, time: 5, sceneTime: 1, dt: .016, dynamicDt: .016, playing: true, lyrics: { index: 1, lines, progress: .3 } };
  for (let i = 0; i < 6; i++) instance.update({ ...frame, now: 1000 + i * 16 });
  const meshes = []; scene.traverse(node => { if (node.material?.uniforms?.uText) meshes.push(node); });
  const retained = meshes.find(node => node.material.uniforms.uText.value?.image && node.userData.lyricKey === '8:Row 2');
  assert.ok(retained, 'rows carry stable source identity');
  const beforeY = retained.position.y;
  instance.update({ ...frame, now: 1100, time: 8.01, lyrics: { ...frame.lyrics, index: 2 } });
  assert.equal(retained.userData.lyricKey, '8:Row 2', 'next active row reuses its existing mesh and texture');
  assert.ok(Math.abs(retained.position.y - beforeY) < 1, 'normal next-line transition moves continuously');
  instance.update({ ...frame, now: 1116, time: 1, dynamicDt: 0, playing: false, lyrics: { ...frame.lyrics, index: 0 } });
  const current = meshes.find(node => node.userData.lyricKey === '0:Row 0');
  assert.ok(Math.abs(current.position.y) < .01, 'paused seeking snaps to the correct reading row');
  instance.dispose(); scope.dispose(); resources.dispose();
  assert.equal(scene.children.length, 0, 'lyric scope releases all scene objects');
  console.log('Space lyric layout checks passed: wrapping, Unicode, texture bounds and measured token timing.');
})().catch(error => { console.error(error); process.exitCode = 1; });
